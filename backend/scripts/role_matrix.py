"""Write the role and permission matrix into docs/roles-and-permissions.md from the code, and the
same grants into the web app's test fixture.

    uv run python -m scripts.role_matrix

The matrix between the two markers in that document is generated from the permission catalog
and the role definitions (app/platform/authz), so the documentation cannot drift from what the
system grants (docs/authorization-model.md §9). `frontend/src/test/role-permissions.json` holds
each role's permission keys, so the navigation tests use the real grants. A contract test fails
when either is out of date.
"""

import json
from pathlib import Path
from typing import Final

from app.platform.authz.catalog import CATALOG
from app.platform.authz.roles import ACCOUNT_BASELINE, ROLES

REPOSITORY: Final = Path(__file__).resolve().parents[2]
DOCUMENT_PATH: Final = REPOSITORY / "docs" / "roles-and-permissions.md"
FIXTURE_PATH: Final = REPOSITORY / "frontend" / "src" / "test" / "role-permissions.json"
START: Final = "<!-- role-matrix:start (generated by `uv run python -m scripts.role_matrix`; do not edit) -->"
END: Final = "<!-- role-matrix:end -->"


def render_matrix() -> str:
    header = ["Permission", "Step-up", "Audited", "Every account", *(f"`{role.key}`" for role in ROLES)]
    lines = [
        "| " + " | ".join(header) + " |",
        "|" + "|".join("---" for _ in header) + "|",
    ]
    for permission in CATALOG:
        cells = [
            f"`{permission.key}`",
            "SU" if permission.step_up else "",
            "R" if permission.audit_reads else "",
            "●" if permission.key in ACCOUNT_BASELINE else "",
            *("●" if permission.key in role.permissions else "" for role in ROLES),
        ]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def render_document(current: str) -> str:
    before, found_start, rest = current.partition(START)
    _, found_end, after = rest.partition(END)
    if not found_start or not found_end:
        raise ValueError(f"{DOCUMENT_PATH.name} must contain the role-matrix markers")
    return f"{before}{START}\n\n{render_matrix()}\n{END}{after}"


def render_fixture() -> str:
    grants = {"account_baseline": sorted(ACCOUNT_BASELINE)} | {
        str(role.key): sorted(role.permissions) for role in ROLES
    }
    return json.dumps(grants, indent=2) + "\n"


if __name__ == "__main__":
    DOCUMENT_PATH.write_text(
        render_document(DOCUMENT_PATH.read_text(encoding="utf-8")), encoding="utf-8", newline="\n"
    )
    FIXTURE_PATH.write_text(render_fixture(), encoding="utf-8", newline="\n")
